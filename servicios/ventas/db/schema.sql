-- Se puede aplicar más de una vez: el esquema usa IF NOT EXISTS y los datos solo entran si la tabla está vacía.
-- libro_id, titulo, autor y precio coinciden con el catálogo de ejemplo de Libros.

CREATE TABLE IF NOT EXISTS venta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libro_id        BIGINT         NOT NULL,
    titulo          VARCHAR(200)   NOT NULL,
    autor           VARCHAR(150)   NOT NULL,
    cantidad        INTEGER        NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    fecha           TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_venta_libro ON venta (libro_id);

